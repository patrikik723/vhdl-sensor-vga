    signal row_counter : integer range 0 to 7 := 0;

begin
     process(clock)
	  variable data_new_variable : std_logic := '0';
	  
begin
    if rising_edge(clock) then
        if reset = '0' then
            row_counter <= 0;
            data_dht <= (others => '0');
				data_ds <= (others => '0');
        else
					data_dht <= rom(to_integer(unsigned(addr_dht)), row_counter);
